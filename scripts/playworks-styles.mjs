import { readFile, writeFile } from 'node:fs/promises'
import postcss from 'postcss'

const source = new URL('../../play-works/src/', import.meta.url)
const chunks = [await readFile(new URL('main.css', source), 'utf8')]
for (const view of ['Advergaming', 'Tvchannels', 'VideoPage']) {
  const text = await readFile(new URL(`views/${view}.vue`, source), 'utf8')
  for (const match of text.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)) chunks.push(match[1])
}
const root = postcss.parse(chunks.join('\n'))
root.walkAtRules('import', rule => rule.remove())
root.walkRules(rule => {
  if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return
  rule.selectors = rule.selectors.map(selector => {
    if (/^(html|body|:root)(?:$|[\s.:#[])/.test(selector)) {
      return selector.replace(/^(html|body|:root)/, '.playworks[data-play-kind]')
    }
    return `.playworks[data-play-kind] ${selector}`
  })
})
root.walkDecls(declaration => {
  declaration.value = declaration.value.replace(/url\((['"]?)(?:\.\.\/)?(?:src\/)?assets\/([^)'"]+)\1\)/g,
    (_match, _quote, name) => `url("/playworks/${name}")`)
})
await writeFile(new URL('../src/styles/playworks-inner.css', import.meta.url),
  `/* Generated by scripts/playworks-styles.mjs from original inner-page styles. */\n${root.toString()}\n`)
console.log('Generated isolated Play.Works inner-page styles')
